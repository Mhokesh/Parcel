const { chromium } = require('../artifacts/browser-test/node_modules/playwright');
const assert = require('node:assert/strict');
(async () => {
  const browser = await chromium.launch({ headless: true });
  const page = await browser.newPage({ viewport: { width: 1440, height: 1050 } });
  const errors = [];
  // Do not automate downloads from community map tile servers.
  await page.route('https://tile.openstreetmap.org/**', route => route.abort());
  page.on('pageerror', e => errors.push(e.message));
  await page.goto('http://127.0.0.1:8000');
  await page.getByText('Your workspace is connected', { exact: true }).waitFor();
  await page.screenshot({ path: 'artifacts/dashboard-desktop-empty.png', fullPage: true });
  await page.locator('[data-tab="orders"]').click();
  assert.equal(await page.locator('#order-rows tr').count(), 50);
  await page.locator('#search').fill('Kavitha');
  assert.equal(await page.locator('#order-rows tr').count(), 1);
  await page.locator('[data-tab="fleet"]').click();
  await page.locator('#plan-button').click();
  await page.getByText('Your dispatch is saved. Choose a vehicle to start delivering.', { exact: true }).waitFor();
  assert.ok(await page.locator('[data-vehicle]').count() > 0);
  await page.locator('[data-vehicle]').first().click();
  await page.evaluate(() => window.scrollTo(0,0));
  await page.waitForTimeout(1200);
  await page.screenshot({ path: 'artifacts/dashboard-desktop-planned.png', fullPage: true });
  await page.locator('[data-event="delivered"]').click();
  await page.getByText('Delivery progress saved.', { exact: true }).waitFor();
  await page.locator('#refresh').click();
  await page.locator('[data-tab="history"]').click();
  await page.locator('[data-dispatch]').first().waitFor();
  await page.locator('[data-dispatch]').first().click();
  assert.ok((await page.locator('#stats').textContent()).includes('Delivered'));
  await page.setViewportSize({ width: 390, height: 844 });
  await page.evaluate(() => window.scrollTo(0,0));
  await page.waitForTimeout(400);
  await page.screenshot({ path: 'artifacts/dashboard-iphone.png', fullPage: true });
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth), false, 'Mobile layout overflows');
  await page.locator('[data-tab="orders"]').click();
  await page.locator('#csv-file').setInputFiles({name:'custom.csv',mimeType:'text/csv',buffer:Buffer.from('id,name,lat,lon,weight_kg\n0,Depot,11,77,0\n100,"<img src=x onerror=alert(1)>",11.01,77.01,2\n')});
  await page.getByText('Orders imported. Review your fleet before planning.', {exact:true}).waitFor();
  await page.locator('#search').fill('');
  assert.equal(await page.locator('#order-rows img').count(),0, 'Order data rendered as HTML');
  assert.equal(await page.locator('#order-rows tr').count(),1);
  assert.deepEqual(errors, []);
  console.log(JSON.stringify({status:'passed', checks:['50 orders','search','fleet planning','route selection','delivery persistence','history','390px layout','CSV import','HTML escaping'], screenshots:3}));
  await browser.close();
})().catch(e => { console.error(e); process.exit(1); });
